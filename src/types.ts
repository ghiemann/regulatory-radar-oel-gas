/**
 * Regulatory Radar – public data model
 *
 * IMPORTANT:
 * This model is for PUBLIC regulatory information only.
 *
 * Do not store:
 * - Harbour Energy positions
 * - internal assessments
 * - internal relevance scores
 * - confidential stakeholder intelligence
 * - information from internal emails, Teams or SharePoint
 * - non-public BVEG / industry discussions
 *
 * Those belong in the future private Policy Tracker layer.
 */

export type Level =
  | "EU"
  | "Bund"
  | "Niedersachsen"
  | "Schleswig-Holstein"
  | "OtherLand";

export type SourceType =
  | "Parlament"
  | "Ministerium"
  | "Behoerde"
  | "Verkuendung"
  | "EUInstitution"
  | "Sonstige";

/**
 * Indicates how strongly the information is verified.
 *
 * "primary-source":
 * Directly retrieved from the responsible public institution.
 *
 * "secondary-confirmed":
 * Information is not from the responsible primary institution,
 * but has been confirmed by a reliable public secondary source.
 *
 * "unverified":
 * Candidate information that still requires verification.
 */
export type VerificationStatus =
  | "primary-source"
  | "secondary-confirmed"
  | "unverified";

/**
 * Describes what is actually new about a document or development.
 *
 * This is deliberately factual rather than a judgement
 * about relevance to any particular company.
 */
export type ChangeType =
  | "new-policy-file"
  | "material-status-change"
  | "new-milestone"
  | "new-document"
  | "stakeholder-position"
  | "duplicate"
  | "no-material-change";

/**
 * Quality information generated by the importer.
 *
 * This helps distinguish:
 * - a clean official record,
 * - an item whose text extraction was incomplete,
 * - an item that requires manual checking.
 */
export type ImportQualityStatus =
  | "clean"
  | "warning"
  | "manual-review";

export type ImportQuality = {
  status: ImportQualityStatus;
  issues: string[];
};

/**
 * Individual public regulatory document or development.
 *
 * policyFileId links individual documents to a persistent
 * regulatory/policy file.
 *
 * Example:
 *
 * policyFileId: "eu-methane-regulation"
 *
 * can later connect several Council, Commission and Parliament
 * documents concerning the same legislative file.
 */
export type RegulatoryDocument = {
  /**
   * Globally unique ID for this particular document/development.
   */
  id: string;

  /**
   * Stable ID of the broader policy file.
   *
   * Optional during migration from v1.
   */
  policyFileId?: string;

  title: string;

  source: string;

  sourceType: SourceType;

  level: Level;

  documentType: string;

  /**
   * Original publication date from the public source.
   *
   * ISO format:
   * YYYY-MM-DD
   */
  publishedAt: string;

  /**
   * Date/time when Regulatory Radar first detected the item.
   *
   * ISO 8601 where possible.
   */
  detectedAt: string;

  /**
   * Most recent successful verification of this record.
   */
  lastCheckedAt: string;

  /**
   * Legacy field retained temporarily for backwards compatibility.
   *
   * Remove once all importers and UI components use
   * publishedAt/detectedAt/lastCheckedAt.
   */
  date?: string;

  /**
   * Last known public activity associated with the record.
   *
   * Retained for backwards compatibility and timeline purposes.
   */
  lastActivityDate: string;

  /**
   * Neutral description of the publicly known status.
   */
  status: string;

  /**
   * Optional structured legislative / regulatory stage.
   *
   * Examples:
   * "Referentenentwurf"
   * "Kabinettsbeschluss"
   * "Bundestag Ausschussberatung"
   * "Trilog"
   * "Verkuendet"
   *
   * Keep this factual and source-based.
   */
  legislativeStage?: string;

  /**
   * Classification of what changed compared with the previous
   * public record for the same policy file.
   */
  changeType?: ChangeType;

  url: string;

  /**
   * Short, neutral public-source summary for cards/lists.
   */
  summaryShort: string;

  /**
   * Longer neutral public-source description.
   */
  summaryLong: string;

  /**
   * Neutral public subject classifications.
   *
   * These are NOT company-specific relevance tags.
   *
   * Examples:
   * ["methan", "erdgas"]
   * ["ccs", "co2-transport"]
   */
  tags: string[];

  /**
   * Verification level of this information.
   */
  verificationStatus: VerificationStatus;

  /**
   * Public REGULATORY SIGNIFICANCE.
   *
   * This should measure characteristics such as:
   * - authority of source
   * - regulatory specificity
   * - formal decision/status
   * - novelty
   * - recency
   *
   * It must NOT represent relevance to Harbour Energy.
   */
  regulatorySignificanceScore: number;

  /**
   * Neutral explanation of the public significance score.
   */
  regulatorySignificanceReason: string;

  /**
   * Legacy v1 scoring fields.
   *
   * Kept temporarily so that the current frontend does not have
   * to be migrated simultaneously.
   *
   * These should be removed once scoring.ts and App.tsx use the
   * new regulatorySignificance fields.
   */
  relevanceScore?: number;
  relevanceReason?: string;

  /**
   * Quality information from the importer.
   */
  importQuality?: ImportQuality;
};

/**
 * Persistent public policy/regulatory file.
 *
 * This will allow Regulatory Radar to move from:
 *
 * "Here are today's documents"
 *
 * toward:
 *
 * "Here is the current publicly documented status of this
 * regulatory file, with a chronology of developments."
 *
 * This type can be introduced without immediately implementing
 * policy-files.json.
 */
export type PolicyFile = {
  /**
   * Stable human-readable ID.
   *
   * Examples:
   * "eu-methane-regulation"
   * "de-kspg"
   * "de-bergrecht"
   */
  id: string;

  title: string;

  level: Level;

  /**
   * Neutral public topic classifications.
   */
  topics: string[];

  /**
   * Latest publicly verified regulatory status.
   */
  currentPublicStatus: string;

  /**
   * Current formal stage where identifiable.
   */
  legislativeStage?: string;

  /**
   * Date of the most recent material PUBLIC development.
   */
  lastMaterialChangeDate?: string;

  /**
   * Next officially documented public milestone.
   *
   * No prediction should be inserted here.
   */
  nextPublicMilestone?: string;

  /**
   * Date of next milestone where publicly documented.
   */
  nextPublicMilestoneDate?: string;

  /**
   * IDs of RegulatoryDocument records belonging to this file.
   */
  documentIds: string[];

  /**
   * Verification status of the current public policy-file status.
   */
  verificationStatus: VerificationStatus;

  /**
   * Used to archive concluded or obsolete policy files without
   * deleting their history.
   */
  active: boolean;
};

export type TaxonomyCategory = {
  id: string;
  label: string;

  /**
   * Public topic-matching weight.
   *
   * Must not encode Harbour-specific commercial or policy priorities.
   */
  weight: number;

  keywords: string[];
};

/**
 * Generic display bucket.
 *
 * Retained so existing UI logic can continue using the familiar
 * high/medium/low structure during migration.
 */
export type ScoreBucket = "high" | "medium" | "low";

/**
 * Schema version written into future generated datasets.
 */
export const PUBLIC_DATA_SCHEMA_VERSION = 2 as const;

export type PublicDataSchemaVersion =
  typeof PUBLIC_DATA_SCHEMA_VERSION;
